def delta_monomial(i,n):
    D=defaultdict(int)
    D[i,n-i,0]+=1
    for k in range(i+1):D[k,i-k,n-i]+=comb(i,k)
    D[0,i,n-i]-=1
    for k in range(n-i+1):D[i,k,n-i-k]-=comb(n-i,k)
    return {e:v for e,v in D.items() if v}
def relation_matrix(n):
    ds=[delta_monomial(i,n) for i in range(1,n)]
    keys=sorted(set().union(*(d.keys() for d in ds)))
    rows=[[d.get(e,0) for d in ds] for e in keys]
    for i in range(1,n):
        row=[0]*(n-1);row[i-1]+=1;row[n-i-1]-=1
        if any(row):rows.append(row)
    return rows or [[0]*(n-1)]
def rank_mod(rows,p):
    A=[[x%p for x in row] for row in rows]
    r=0
    for j in range(len(A[0])):
        pivot=next((k for k in range(r,len(A)) if A[k][j]),None)
        if pivot is None:continue
        A[r],A[pivot]=A[pivot],A[r]
        inv=pow(A[r][j],-1,p);A[r]=[(v*inv)%p for v in A[r]]
        for k in range(len(A)):
            if k!=r and A[k][j]:
                factor=A[k][j];A[k]=[(u-factor*v)%p for u,v in zip(A[k],A[r])]
        r+=1
    return r
