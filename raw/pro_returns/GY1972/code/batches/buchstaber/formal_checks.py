# Four-variable sparse polynomials over F_p[a,x,y,z]/(a^2).
def add(P,Q,p,sign=1):
    R=dict(P)
    for e,v in Q.items():R[e]=(R.get(e,0)+sign*v)%p
    return {e:v for e,v in R.items() if v}
def mul(P,Q,p):
    R=defaultdict(int)
    for e,v in P.items():
        for f,w in Q.items():
            g=tuple(ei+fi for ei,fi in zip(e,f))
            if g[0]<2:R[g]=(R[g]+v*w)%p
    return {e:v for e,v in R.items() if v}
def power(P,n,p):
    R={(0,0,0,0):1}
    for _ in range(n):R=mul(R,P,p)
    return R
AA={(1,0,0,0):1};XX={(0,1,0,0):1};YY={(0,0,1,0):1};ZZZ={(0,0,0,1):1}

def dn_add(u,v,p):return ((u[0]+v[0])%p,(u[1]+v[1])%p)
def dn_mul(u,v,p):return (u[0]*v[0]%p,(u[0]*v[1]+u[1]*v[0])%p)
def dn_pow(u,n,p):
    v=(1,0)
    for _ in range(n):v=dn_mul(v,u,p)
    return v

