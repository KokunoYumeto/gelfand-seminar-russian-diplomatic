function buildChapter(talks,items,problems) {
 const escape=s=>String(s??"").replace(/[\\{}$&%#_^~]/g,c=>({"\\":"\\textbackslash{}","{":"\\{","}":"\\}","$":"\\$","&":"\\&","%":"\\%","#":"\\#","_":"\\_","^":"\\textasciicircum{}","~":"\\textasciitilde{}"})[c]);
 const fields=[["notes","Notebook content"],["statement","Precise statement"],["reconstruction","Editorial reconstruction"],["fate","Literature and fate"],["present_status","Present status"],["worth","Assessment"]];
 const out=["% Reconstructed text serializer; not generated by the unavailable supplied builder.","\\chapter{Seminar records 597 and 599--639}","\\label{ch:GY1983}","\\input{GY1983_overview.tex}","\\section{Talks and mathematical occurrences}"];
 for(const t of talks) {
  out.push("\\subsection{Record "+t.record+": "+escape(t.title)+"}","\\label{talk:"+t.record+"}","\\noindent\\textbf{Date:} "+escape(t.date)+". \\textbf{Speaker:} "+escape(t.speaker)+". \\textbf{Pages:} "+escape(t.pages)+".\\par",t.summary||"");
  for(const i of items.filter(i=>i.record===t.record)) {
   out.push("\\subsubsection{"+escape(i.id)+" --- "+escape(i.title)+"}","\\label{item:"+i.id+"}","\\noindent\\textbf{Kind:} "+escape(i.kind)+". \\textbf{Fate:} "+i.class+". \\textbf{Pages:} "+escape(i.pages)+".\\par");
   for(const [f,label]of fields)if(i[f])out.push("\\paragraph{"+label+".} "+i[f]);
   out.push("\\paragraph{Audit.} Literal correctness: "+escape(i.literal_correctness)+". Publication match: "+escape(i.publication_match)+". Verification: "+escape(i.verification)+". Development: "+escape(i.development)+". Confidence: "+escape(i.confidence)+".");
   if(i.problem)out.push("\\noindent Canonical problem: "+escape(i.problem)+".\\par");
   if(i.refs?.length)out.push("\\noindent References: \\citep{"+i.refs.join(",")+"}.\\par");
  }
 }
 out.push("\\section{Canonical problem index}");
 for(const p of problems) {
  out.push("\\subsection{"+escape(p.id)+" --- "+escape(p.title)+"}","\\label{problem:"+p.id+"}",p.statement||"","\\paragraph{Occurrences.} "+escape((p.occurrences||[]).join(", "))+".","\\paragraph{Status.} "+(p.status||p.present_status||p.fate||""));
  if(p.scope)out.push("\\paragraph{Scope.} "+p.scope);
  if(p.worth)out.push("\\paragraph{Assessment.} "+p.worth);
  if(p.refs?.length)out.push("\\noindent\\citep{"+p.refs.join(",")+"}.");
 }
 out.push("\\section{Mathematical developments}", "\\input{GY1983_development.tex}");
 return out.join("\n\n")+"\n";
}
if(typeof module!=="undefined"&&module.exports){
 module.exports={buildChapter};
 if(require.main===module){
  const fs=require("fs"),path=require("path"),base=__dirname;
  const read=n=>JSON.parse(fs.readFileSync(path.join(base,n),"utf8"));
  fs.writeFileSync(path.join(base,"GY1983_chapter.tex"),buildChapter(read("GY1983_talks.json"),read("GY1983_items.json"),read("GY1983_problems.json")),"utf8");
 }
}
